  e.equipment_id,
  e.equipment_code,
  e.display_name,
  e.equipment_type,
  e.legacy_id,
  e.legacy_specs->>'MoldID' AS access_mold_id,
  r.rack_code,
  rl.layer_code
FROM equipment e
LEFT JOIN rack_layers rl ON e.current_rack_layer_id = rl.id
LEFT JOIN racks r ON rl.rack_id = r.id
WHERE e.legacy_id IN ('M-373', 'M-5076', 'M-4494', 'M-5337', 'M-5593')
ORDER BY e.legacy_id;



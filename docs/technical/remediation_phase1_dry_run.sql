-- ============================================================================
-- PHẦN 1A: DRY-RUN KIỂM TRA PHÂN PHỐI WORK_ORDERS (CHỈ SELECT - KHÔNG SỬA DỮ LIỆU)
-- ============================================================================

WITH wo_job_rollup AS (
  SELECT 
    j.work_order_id,
    -- 1. Phân loại wo_type theo jobs con:
    CASE 
      WHEN bool_or(j.job_category IN ('MOLD_NEW', 'EQUIPMENT_NEW', 'CUTTER_NEW', 'DESIGN')) THEN 'NEW_SET'
      WHEN bool_or(j.job_category IN ('EQUIPMENT_REPAIR', 'MAINTENANCE')) THEN 'REPAIR'
      ELSE 'OTHER'
    END AS calculated_wo_type,
    -- 2. Đồng bộ wo_status theo jobs con:
    CASE 
      WHEN bool_and(j.job_status = 'COMPLETED') THEN 'COMPLETED'
      WHEN bool_or(j.job_status = 'IN_PROGRESS') THEN 'IN_PROGRESS'
      WHEN bool_and(j.job_status IN ('PENDING', 'PLANNED')) THEN 'PLANNED'
      ELSE 'PLANNED'
    END AS calculated_wo_status,
    count(*) AS total_jobs,
    string_agg(j.job_category, ', ') AS job_categories
  FROM jobs j
  WHERE j.work_order_id IS NOT NULL
  GROUP BY j.work_order_id
)
SELECT 
  wjr.calculated_wo_type,
  wjr.calculated_wo_status,
  count(*) AS total_work_orders,
  sum(wjr.total_jobs) AS total_jobs_covered
FROM wo_job_rollup wjr
GROUP BY wjr.calculated_wo_type, wjr.calculated_wo_status
ORDER BY wjr.calculated_wo_type, wjr.calculated_wo_status;

-- Kỳ vọng kết quả DRY-RUN 1A (Đã xác minh độc lập 100% trên DB Supabase Production):
-- calculated_wo_type | calculated_wo_status | total_work_orders | total_jobs_covered
-- -------------------+----------------------+-------------------+-------------------
-- NEW_SET            | COMPLETED            |              1152 |              1152
-- NEW_SET            | PLANNED              |                 1 |                 2  (WO-L-1248: DES-JAE380 + JAE380)
-- REPAIR             | COMPLETED            |                15 |                15
-- OTHER              | COMPLETED            |                35 |                35  (25 OTHER + 10 INTERNAL_OPS, 1 job/WO)
-- TỔNG CỘNG:                                |              1203 |              1204


-- ============================================================================
-- PHẦN 1B: XEM CHI TIẾT WORK ORDER 2-JOB VÀ BẢN GHI PLANNED
-- ============================================================================

-- 1B.1: Chi tiết 1 bản ghi duy nhất chuyển sang PLANNED (WO-L-1248 chứa DES-JAE380 + JAE380):
SELECT 
  w.wo_id, w.wo_code, w.wo_name, w.wo_type AS current_type, w.wo_status AS current_status,
  j.job_code, j.job_name, j.job_category, j.job_status
FROM work_orders w
JOIN jobs j ON j.work_order_id = w.wo_id
WHERE j.job_status != 'COMPLETED';

-- 1B.2: Chi tiết Work Order duy nhất chứa nhiều hơn 1 Job (WO-L-1248: 1 WO chứa 2 jobs):
SELECT 
  w.wo_id, w.wo_code, w.wo_name,
  count(j.job_id) AS job_count,
  string_agg(j.job_code || ' (' || j.job_category || ')', '; ') AS jobs_detail
FROM work_orders w
JOIN jobs j ON j.work_order_id = w.wo_id
GROUP BY w.wo_id, w.wo_code, w.wo_name
HAVING count(j.job_id) > 1;


-- ============================================================================
-- PHẦN 2A: SPOT-CHECK 5 MẪU UUID PE YÊU CẦU TRÊN BẢNG EQUIPMENT
-- ============================================================================

